"""
Programaçao Orientada a Objetos - POO

- POO e um paradigma de programaçao que utiliza mapeamento
de objetos do mundo real para modelos computacionais.

- Paradigma de programaçao e a forma utilizadas para
pensar/desenvolver sistemas.

- Principais elementos da Orientaçao a Objetos
- Classe -> Modelo do objeto do mundo real sendo representado computacionalmente;
- Atributo -> Caracteristicas do objeto.
- Metodo -> Comportamento do objeto (funçoes).
- Construtor -> Metodo especial utilizado para criar objetos;
- Objeto -> Instancia da classe

"""

